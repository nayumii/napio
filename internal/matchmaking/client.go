// Package matchmaking publishes a public server-browser listing for a Factorio
// server that is currently asleep, and withdraws it the moment the real server
// takes over.
//
// The protocol is undocumented by Wube. Everything here was captured from a
// real Factorio 2.0.77 headless server and then verified against the live
// service; see docs/MATCHMAKING.md. It is therefore version-fragile by nature,
// and every failure path in this package is designed to be non-fatal: a
// listing that cannot be published must never stop napio from waking or
// sleeping a server.
package matchmaking

import (
	"bytes"
	"context"
	"crypto/rand"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"time"
)

// DefaultBaseURL is Factorio's matching service.
const DefaultBaseURL = "https://multiplayer.factorio.com"

// HeartbeatInterval is how often a real Factorio server heartbeats its
// listing, measured over 14 consecutive beats from a live 2.0.77 server.
// napio uses the same cadence: no faster, so the service is never hammered.
const HeartbeatInterval = 30 * time.Second

// noGameID is the "no id yet" sentinel a real server sends in create-game.
const noGameID = 4294967295

// Version identifies the Factorio build behind the listing. Every field is
// observed from the real server; none of it is guessed.
type Version struct {
	GameVersion  string `json:"game_version"`
	BuildVersion int    `json:"build_version"`
	BuildMode    string `json:"build_mode"`
	Platform     string `json:"platform"`
}

// Mod is one entry of the advertised mod list.
type Mod struct {
	Name    string `json:"name"`
	Version string `json:"version"`
}

// Game is the listing body sent to create-game.
type Game struct {
	GameID      uint32   `json:"game_id"`
	GameSecret  string   `json:"game_secret"`
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Tags        []string `json:"tags,omitempty"`
	Version     Version  `json:"application_version"`
	MaxPlayers  int      `json:"max_players"`
	HasPassword bool     `json:"has_password"`
	HostAddress string   `json:"host_address"`
	HostPort    int      `json:"host_port"`
	Mods        []Mod    `json:"mods,omitempty"`
	Headless    bool     `json:"headless_server"`
	// GameTimeElapsed is deliberately omitted rather than guessed: napio
	// cannot observe the tick count while the server is off, and the live
	// service accepts a listing without it.
}

// Credentials are a factorio.com account username and token. The token is a
// secret: it is never logged, never returned by the API and never included in
// an error message.
type Credentials struct {
	Username string
	Token    string
}

// Client talks to the matching service.
type Client struct {
	BaseURL string
	HTTP    *http.Client
}

// NewClient returns a client with sensible timeouts.
func NewClient(baseURL string) *Client {
	if baseURL == "" {
		baseURL = DefaultBaseURL
	}
	return &Client{
		BaseURL: baseURL,
		HTTP:    &http.Client{Timeout: 20 * time.Second},
	}
}

// Listing identifies a published listing.
type Listing struct {
	GameID uint32
	// Secret is generated by us and echoed on every later request. The live
	// service returns its own server_secret, which the real Factorio server
	// ignores in favour of the one it generated; napio does the same.
	Secret string
}

// NewSecret generates the 32-character secret a server uses to prove it owns
// its listing.
func NewSecret() (string, error) {
	const alphabet = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("generating listing secret: %w", err)
	}
	for i, b := range buf {
		buf[i] = alphabet[int(b)%len(alphabet)]
	}
	return string(buf), nil
}

type createRequest struct {
	Game     Game   `json:"game"`
	Username string `json:"username"`
	Token    string `json:"token"`
}

type createResponse struct {
	GameID uint32 `json:"game_id"`
}

// Create publishes a new listing.
func (c *Client) Create(ctx context.Context, game Game, creds Credentials) (Listing, error) {
	secret, err := NewSecret()
	if err != nil {
		return Listing{}, err
	}
	game.GameID = noGameID
	game.GameSecret = secret
	game.Headless = true

	body, err := c.post(ctx, "/create-game", createRequest{
		Game:     game,
		Username: creds.Username,
		Token:    creds.Token,
	})
	if err != nil {
		return Listing{}, err
	}
	var out createResponse
	if err := json.Unmarshal(body, &out); err != nil || out.GameID == 0 {
		return Listing{}, fmt.Errorf("create-game: unexpected response: %s", clip(body))
	}
	return Listing{GameID: out.GameID, Secret: secret}, nil
}

type heartbeatRequest struct {
	Secret string         `json:"game_secret"`
	Patch  map[string]any `json:"game_patch"`
}

// Heartbeat keeps a listing alive. patch may be nil: the service accepts an
// empty patch, and a sleeping server has nothing that changes.
func (c *Client) Heartbeat(ctx context.Context, listing Listing, patch map[string]any) error {
	if patch == nil {
		patch = map[string]any{}
	}
	_, err := c.post(ctx, fmt.Sprintf("/post-game-heartbeat/%d", listing.GameID),
		heartbeatRequest{Secret: listing.Secret, Patch: patch})
	return err
}

type removeRequest struct {
	Secret string `json:"game_secret"`
}

// Remove withdraws a listing.
func (c *Client) Remove(ctx context.Context, listing Listing) error {
	_, err := c.post(ctx, fmt.Sprintf("/remove-game/%d", listing.GameID),
		removeRequest{Secret: listing.Secret})
	return err
}

func (c *Client) post(ctx context.Context, path string, payload any) ([]byte, error) {
	encoded, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.BaseURL+path, bytes.NewReader(encoded))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "napio (+https://git.naknu.li/emily/napio)")

	resp, err := c.HTTP.Do(req)
	if err != nil {
		// The URL is safe to show; the credentials are in the body, not here.
		return nil, fmt.Errorf("matchmaking %s: %w", path, err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return nil, fmt.Errorf("matchmaking %s: reading response: %w", path, err)
	}
	if resp.StatusCode != http.StatusOK {
		return nil, &HTTPError{Path: path, Status: resp.StatusCode, Body: clip(body)}
	}
	return body, nil
}

// HTTPError is a non-200 answer from the matching service.
type HTTPError struct {
	Path   string
	Status int
	Body   string
}

func (e *HTTPError) Error() string {
	return fmt.Sprintf("matchmaking %s: HTTP %d: %s", e.Path, e.Status, e.Body)
}

// Fatal reports whether retrying is pointless: a rejected token or a malformed
// request will not fix itself, so the agent stops instead of hammering the
// service.
func (e *HTTPError) Fatal() bool {
	return e.Status == http.StatusUnauthorized || e.Status == http.StatusForbidden
}

func clip(body []byte) string {
	const max = 300
	s := string(bytes.TrimSpace(body))
	if len(s) > max {
		return s[:max] + "…"
	}
	return s
}
